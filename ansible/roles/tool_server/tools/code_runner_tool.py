import base64
import docker
import logging
import os
import shutil
import subprocess
import tempfile
from llm_sandbox import SandboxSession
from typing import List, Optional


class ApptainerSandboxExecutor:
    """Executes code using Apptainer / Singularity unprivileged HPC containers."""

    def __init__(
        self,
        sif_image: Optional[str] = None,
        workspace_dir: Optional[str] = None,
        bind_paths: Optional[List[str]] = None,
        allow_privileged: bool = False,
        drop_caps: bool = True,
    ):
        self.sif_image = sif_image or os.environ.get(
            "APPTAINER_IMAGE",
            os.environ.get("SINGULARITY_IMAGE", "/opt/apptainer/images/hermes_sandbox.sif")
        )
        self.workspace_dir = workspace_dir or os.environ.get(
            "APPTAINER_WORKDIR", "/var/lib/openclaw/workspace"
        )
        default_binds = [
            "/opt/nomad/volumes:/opt/nomad/volumes",
            "/opt/unified_fs_backend:/opt/unified_fs_backend",
        ]
        env_binds = os.environ.get("APPTAINER_BIND_PATHS")
        if env_binds:
            self.bind_paths = [b.strip() for b in env_binds.split(",") if b.strip()]
        else:
            self.bind_paths = bind_paths if bind_paths is not None else default_binds

        self.allow_privileged = allow_privileged
        self.drop_caps = drop_caps
        self.executable = shutil.which("apptainer") or shutil.which("singularity") or "apptainer"

    def run_command(self, command: str, timeout: int = 60) -> dict:
        """Runs a shell command inside the Apptainer/Singularity container sandbox."""
        cmd = [self.executable, "exec"]
        if self.drop_caps:
            cmd.append("--drop-caps")
        if not self.allow_privileged:
            cmd.append("--no-privs")

        if os.path.exists(self.workspace_dir):
            cmd.extend(["--bind", f"{self.workspace_dir}:/workspace", "--pwd", "/workspace"])

        for b in self.bind_paths:
            src = b.split(":")[0] if ":" in b else b
            if os.path.exists(src):
                cmd.extend(["--bind", b])

        cmd.extend([self.sif_image, "bash", "-c", command])

        try:
            res = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=timeout,
                check=False
            )
            return {
                "exit_code": res.returncode,
                "stdout": res.stdout,
                "stderr": res.stderr
            }
        except subprocess.TimeoutExpired:
            return {
                "exit_code": -1,
                "stdout": "",
                "stderr": f"Execution timed out inside Apptainer sandbox after {timeout} seconds."
            }
        except Exception as e:
            return {
                "exit_code": -1,
                "stdout": "",
                "stderr": f"Apptainer execution error: {e}"
            }

    def execute(
        self,
        code: str,
        language: str = "python",
        libraries: Optional[List[str]] = None,
        timeout: Optional[int] = None
    ) -> str:
        job_timeout = timeout if timeout is not None else 60
        if language == "python":
            install_prefix = f"pip install {' '.join(libraries)} >/dev/null 2>&1 && " if libraries else ""
            code_b64 = base64.b64encode(code.encode("utf-8")).decode("utf-8")
            py_cmd = f"{install_prefix}python3 -c 'import base64; exec(base64.b64decode(\"{code_b64}\").decode(\"utf-8\"))'"
            result = self.run_command(py_cmd, timeout=job_timeout)
        else:
            result = self.run_command(code, timeout=job_timeout)

        if result["exit_code"] == 0:
            return result["stdout"]
        else:
            err = result["stderr"] or result["stdout"]
            return f"Exit Code: {result['exit_code']}\n---STDERR---\n{err}"


SingularitySandboxExecutor = ApptainerSandboxExecutor


class CodeRunnerTool:
    """A tool for executing Python code in a sandboxed Docker container.

    This class provides a method to run arbitrary Python code within a
    secure, isolated, and ephemeral Docker container. It's designed to
    safely execute code generated by the LLM.

    Attributes:
        description (str): A brief description of the tool's purpose.
        name (str): The name of the tool.
        client: The Docker client instance.
        image (str): The name of the Docker image to use for the container.
    """
    def __init__(self):
        """Initializes the CodeRunnerTool."""
        self.description = "Execute Python code in a sandboxed Docker container."
        self.name = "code_runner"
        self.client = docker.from_env()
        self.image = "python:3.9-slim"

    def run_python_code(self, code: str) -> str:
        """Runs a string of Python code in a Docker container and returns the output.

        The code is written to a temporary file, which is mounted read-only
        into a `python:3.9-slim` container. The container executes the script
        and its combined stdout and stderr are captured and returned.

        Args:
            code (str): The Python code to execute.

        Returns:
            str: The captured output (stdout and stderr) from the code
                 execution, or an error message if something went wrong.
        """
        try:
            with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as tmp_file:
                tmp_file.write(code)
                tmp_file_path = tmp_file.name

            container_path = f"/tmp/{os.path.basename(tmp_file_path)}"

            container = self.client.containers.run(
                self.image,
                command=["python", container_path],
                volumes={os.path.dirname(tmp_file_path): {'bind': '/tmp', 'mode': 'ro'}},
                remove=True,
                stderr=True,
                stdout=True
            )

            output = container.decode('utf-8')
            return output

        except docker.errors.ImageNotFound:
            return f"Error: The Docker image '{self.image}' was not found. Please pull it first."
        except Exception as e:
            return f"An error occurred: {e}"
        finally:
            if 'tmp_file_path' in locals() and os.path.exists(tmp_file_path):
                os.unlink(tmp_file_path)

    def run_code_in_sandbox(
        self,
        code: str,
        language: str = "python",
        libraries: Optional[List[str]] = None
    ) -> str:
        """Runs code in a secure llm-sandbox, with support for multiple languages.

        Args:
            code (str): The code to execute.
            language (str): The programming language. Defaults to "python".
                            Supported: python, javascript, java, cpp, go, r.
            libraries (Optional[List[str]]): A list of libraries to install.

        Returns:
            str: The execution output or an error message.
        """
        if libraries is None:
            libraries = []

        try:
            with SandboxSession(lang=language) as session:
                result = session.run(code, libraries=libraries)
                if result.exit_code == 0:
                    output = result.stdout
                else:
                    output = f"Exit Code: {result.exit_code}\n---STDERR---\n{result.stderr}\n---STDOUT---\n{result.stdout}"

                if result.plots:
                    output += "\n\nGenerated plots are available."

                return output
        except Exception as e:
            return f"An unexpected error occurred: {e}"
